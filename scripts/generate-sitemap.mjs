#!/usr/bin/env node
/**
 * generate-sitemap.mjs — the sitemap for the static export, including the
 * public entity profiles.
 *
 *   npm run emit:sitemap -- --origin https://puppetnet-web.pages.dev
 *   SITE_ORIGIN=https://console.example node scripts/generate-sitemap.mjs
 *
 * The sitemap is generated, never committed: every `<loc>` must be absolute and
 * the repository does not know its deployment domain. `scripts/emit-seo-files.mjs`
 * calls the same functions during the Pages build, so `robots.txt`, the sitemap
 * and the profile pages always describe the same URL set.
 *
 * Only profiles that exist in the export are listed. `entities.json` is written
 * by `scripts/emit-entity-data.ts` from a pipeline publication; without it the
 * committed demo dataset is used, exactly like the Next build. A URL that does
 * not resolve is worse than an absent sitemap entry, so unknown records are
 * skipped — never guessed.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SITEMAP_LIMIT = 50_000;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SLUG = /^[a-z0-9][a-z0-9-]{0,80}$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;

export function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function normalizeOrigin(raw) {
  const url = new URL(String(raw));
  if (!/^https?:$/.test(url.protocol)) throw new Error('origin must be http(s)');
  if (url.username || url.password) throw new Error('origin must not contain credentials');
  if (url.pathname !== '/' || url.search || url.hash) throw new Error('origin must not have a path, query or fragment');
  return url.origin;
}

function isoDate(value, fallback) {
  const candidate = typeof value === 'string' ? value.slice(0, 10) : '';
  return DATE.test(candidate) ? candidate : fallback;
}

export function priorityForType(type) {
  switch (type) {
    case 'Person':
    case 'Organization':
      return '0.7';
    case 'Location':
      return '0.6';
    case 'Craft':
      return '0.5';
    default:
      return '0.4';
  }
}

/** Public, unique, well-formed profile URLs. */
export function entityEntries(entities, generatedAt) {
  const seen = new Set();
  const entries = [];
  for (const entity of Array.isArray(entities) ? entities : []) {
    if (!entity || typeof entity !== 'object') continue;
    if (entity.public === false || entity.noindex === true) continue;
    const slug = typeof entity.slug === 'string' ? entity.slug.trim() : '';
    if (!SLUG.test(slug) || seen.has(slug)) continue;
    seen.add(slug);
    entries.push({
      loc: `/entity/${slug}/`,
      lastmod: isoDate(entity.updatedAt ?? entity.updated_at, generatedAt),
      changefreq: 'monthly',
      priority: priorityForType(entity.type),
    });
  }
  return entries.sort((left, right) => left.loc.localeCompare(right.loc));
}

function renderUrl(entry, lastmod) {
  const loc = String(entry.loc || '/');
  const stamp = isoDate(entry.lastmod, lastmod);
  return `  <url>
    <loc>${escapeXml(loc)}</loc>
    <lastmod>${stamp}</lastmod>
    <changefreq>${entry.changefreq || 'monthly'}</changefreq>
    <priority>${entry.priority || '0.5'}</priority>
  </url>`;
}

/** One `<urlset>`; `loc` values are relative and prefixed with the origin. */
export function renderUrlset(entries, origin, lastmod) {
  const urls = entries.map((entry) => renderUrl({ ...entry, loc: `${origin}${entry.loc}` }, lastmod)).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated at build time by scripts/generate-sitemap.mjs from the deployment
     origin; git-ignored, never committed. ${entries.length} URL(s). -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

export function renderSitemapIndex(children, origin, lastmod) {
  const rows = children.map((name) => `  <sitemap>
    <loc>${escapeXml(`${origin}/${name}`)}</loc>
    <lastmod>${lastmod}</lastmod>
  </sitemap>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Sitemap index generated by scripts/generate-sitemap.mjs. -->
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${rows}
</sitemapindex>
`;
}

/**
 * Returns `{ files, urlCount }`. Up to 50 000 URLs that is a single
 * `sitemap.xml`; above it the protocol requires an index and child sitemaps.
 */
export function renderSitemaps({ origin, entries, lastmod, limit = SITEMAP_LIMIT }) {
  const cleanOrigin = normalizeOrigin(origin);
  const stamp = isoDate(lastmod, new Date().toISOString().slice(0, 10));
  const list = entries.filter((entry) => entry && typeof entry.loc === 'string' && entry.loc.startsWith('/'));
  if (list.length <= limit) {
    return {
      urlCount: list.length,
      files: [{ name: 'sitemap.xml', xml: renderUrlset(list, cleanOrigin, stamp) }],
    };
  }
  const files = [];
  for (let index = 0; index < list.length; index += limit) {
    const chunk = list.slice(index, index + limit);
    files.push({ name: `sitemap-${index / limit + 1}.xml`, xml: renderUrlset(chunk, cleanOrigin, stamp) });
  }
  return {
    urlCount: list.length,
    files: [
      { name: 'sitemap.xml', xml: renderSitemapIndex(files.map((file) => file.name), cleanOrigin, stamp) },
      ...files,
    ],
  };
}

/** Pipeline publication first, committed demo second. */
export function loadEntityExport(root = ROOT, explicit) {
  const directory = path.join(root, 'apps', 'web', 'public', 'data');
  const candidates = explicit ? [explicit] : [path.join(directory, 'graph_latest.json'), path.join(directory, 'entities.json'), path.join(directory, 'entities.sample.json')];
  for (const file of candidates) {
    if (!existsSync(file)) continue;
    const raw = JSON.parse(readFileSync(file, 'utf8'));
    return {
      file,
      demo: raw.demo === true || file.endsWith('.sample.json'),
      generatedAt: isoDate(raw.generatedAt ?? raw.generated_at, new Date().toISOString().slice(0, 10)),
      entities: Array.isArray(raw.entities) ? raw.entities : Array.isArray(raw.nodes) ? raw.nodes : [],
    };
  }
  return { file: '', demo: true, generatedAt: new Date().toISOString().slice(0, 10), entities: [] };
}

export function writeSitemaps(directory, files) {
  for (const file of files) {
    writeFileSync(path.join(directory, file.name), file.xml, 'utf8');
  }
}

/* ------------------------------------------------------------------------- */
/* CLI                                                                       */
/* ------------------------------------------------------------------------- */

function argument(argv, name) {
  const index = argv.indexOf(name);
  return index >= 0 ? argv[index + 1] : '';
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const argv = process.argv.slice(2);
  const rawOrigin = argument(argv, '--origin') || process.env.SITE_ORIGIN || '';
  if (!rawOrigin) {
    console.error('generate-sitemap: pass --origin https://… or set SITE_ORIGIN. A relative <loc> is invalid.');
    process.exit(1);
  }
  let origin;
  try {
    origin = normalizeOrigin(rawOrigin);
  } catch (error) {
    console.error(`generate-sitemap: "${rawOrigin}" is not a usable origin (${error.message}).`);
    process.exit(1);
  }
  const explicit = argument(argv, '--data');
  const out = path.resolve(ROOT, argument(argv, '--out') || 'apps/web/public');
  let dataset;
  try {
    dataset = loadEntityExport(ROOT, explicit || undefined);
  } catch (error) {
    console.error(`generate-sitemap: could not read the entity export (${error.message}).`);
    process.exit(1);
  }
  const lastmod = dataset.generatedAt;
  const staticEntries = [
    { loc: '/', lastmod, changefreq: 'weekly', priority: '1.0' },
    { loc: '/en/', lastmod, changefreq: 'weekly', priority: '0.8' },
    { loc: '/dashboard/', lastmod, changefreq: 'monthly', priority: '0.9' },
    { loc: '/legal/', lastmod, changefreq: 'yearly', priority: '0.3' },
  ];
  const profiles = entityEntries(dataset.entities, lastmod);
  const { files, urlCount } = renderSitemaps({
    origin,
    entries: [...staticEntries, ...profiles],
    lastmod,
    limit: Number(argument(argv, '--limit')) || SITEMAP_LIMIT,
  });
  writeSitemaps(out, files);
  console.log(
    `generate-sitemap: ${urlCount} URL(s) — ${profiles.length} Profil(e) — `
    + `${files.length} Datei(en) in ${path.relative(ROOT, out)} (Quelle: ${dataset.file ? path.relative(ROOT, dataset.file) : 'keine'})`,
  );
}

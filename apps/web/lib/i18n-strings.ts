export type StringKey = keyof typeof DE;
export const DICTIONARIES: Record<Language, Record<StringKey, string>> = { de: DE, en: EN };
export const STRING_KEYS = Object.keys(DE) as StringKey[];

/**
 * Translate with `{param}` substitution. Unknown keys fall back to the German
 * value, then to the key itself, so a missing translation can never render an
 * empty string into the accessibility tree.
 */
export function translate(lang: Language, key: StringKey | string, params?: Params): string {
  const value = DICTIONARIES[lang][key as StringKey] ?? DICTIONARIES.de[key as StringKey] ?? String(key);
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}
